"use client"

import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { SearchIcon } from "lucide-react"

import { cn } from "@/lib/utils"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"

// Figma 02 Command `4:247` (v2 restyle) is the command palette: CommandDialog carries its
// chrome (radius/2xl, elevation/3, padding space/2, 360 wide, a bordered 40-high search
// field, items 4 apart; the highlighted item is accent with a 2px ring). The bare Command
// surface stays chrome-less because Combobox composes it inside a Popover.

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "bg-popover text-popover-foreground flex h-full w-full flex-col overflow-hidden rounded-xl",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
}) {
  return (
    <Dialog {...props}>
      <DialogHeader className="sr-only">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
      </DialogHeader>
      <DialogContent
        data-slot="command-dialog"
        className={cn("gap-0 overflow-hidden p-2 sm:max-w-[360px]", className)}
        showCloseButton={showCloseButton}
      >
        <Command className="gap-1 rounded-none **:data-[slot=command-input-wrapper]:h-10 **:data-[slot=command-input-wrapper]:rounded-lg **:data-[slot=command-input-wrapper]:border **:data-[slot=command-input-wrapper]:border-input **:data-[slot=command-input-wrapper]:bg-background [&_[data-slot=command-input-wrapper]:focus-within]:border-primary [&_[data-slot=command-input-wrapper]:focus-within]:shadow-focus-ring [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group]]:p-0 [&_[cmdk-group-items]]:flex [&_[cmdk-group-items]]:flex-col [&_[cmdk-group-items]]:gap-1 [&_[cmdk-item][data-selected=true]]:ring-2 [&_[cmdk-item][data-selected=true]]:ring-ring [&_[cmdk-item][data-selected=true]]:ring-inset">
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}

