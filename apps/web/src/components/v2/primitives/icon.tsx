export type IconName = keyof typeof iconMap;

export const iconNames = Object.keys(iconMap) as IconName[];

export function isIconName(value: string): value is IconName {
  return Object.prototype.hasOwnProperty.call(iconMap, value);
}

/** Figma glyphs use stroke 1.75 on a 24 grid. */
export const ICON_STROKE_WIDTH = 1.75;

type IconProps = Omit<LucideProps, "ref"> & { name: IconName };

/** Renders a Figma `Icon/<name>` glyph. Decorative by default (aria-hidden). */
export function Icon({ name, size = 16, strokeWidth = ICON_STROKE_WIDTH, className, ...props }: IconProps) {
  const Glyph = iconMap[name];
  return (
    <Glyph
      data-slot="icon"
      data-icon={name}
      aria-hidden={props["aria-label"] ? undefined : true}
      size={size}
      strokeWidth={strokeWidth}
      className={cn("shrink-0", className)}
      {...props}
    />
  );
}
